import type { ReactNode } from 'react';
import { FlaskConical } from 'lucide-react';
import { cn } from '@/lib/cn';
import { PO_STATUS, SEVERITY, SHIPMENT_STATUS, SOURCE, type Tone } from '@/lib/constants';
import type { AlertSeverity, PoStatus, QuoteSourceType, ShipmentStatus } from '@/lib/types';

const tones: Record<Tone, string> = {
  neutral: 'bg-surface-3 text-muted border-line',
  accent: 'bg-accent-soft text-accent border-transparent',
  success: 'bg-success-soft text-success border-transparent',
  warning: 'bg-warning-soft text-warning border-transparent',
  danger: 'bg-danger-soft text-danger border-transparent',
  info: 'bg-info-soft text-info border-transparent',
  sim: 'bg-sim-soft text-sim border-transparent',
};

const dots: Record<Tone, string> = {
  neutral: 'bg-subtle',
  accent: 'bg-accent',
  success: 'bg-success',
  warning: 'bg-warning',
  danger: 'bg-danger',
  info: 'bg-info',
  sim: 'bg-sim',
};

export function Badge({ tone = 'neutral', dot, children, className, title }: { tone?: Tone; dot?: boolean; children: ReactNode; className?: string; title?: string }) {
  return (
    <span title={title} className={cn('inline-flex items-center gap-1.5 rounded-md border px-2 py-0.5 text-xs font-medium whitespace-nowrap', tones[tone], className)}>
      {dot && <span className={cn('h-1.5 w-1.5 rounded-full', dots[tone])} aria-hidden />}
      {children}
    </span>
  );
}

export function StatusBadge({ status }: { status: ShipmentStatus }) {
  const s = SHIPMENT_STATUS[status];
  return (
    <Badge tone={s.tone} dot>
      {s.label}
    </Badge>
  );
}

export function PoStatusBadge({ status }: { status: PoStatus }) {
  const s = PO_STATUS[status];
  return (
    <Badge tone={s.tone} dot>
      {s.label}
    </Badge>
  );
}

export function SeverityBadge({ severity }: { severity: AlertSeverity }) {
  const s = SEVERITY[severity];
  return (
    <Badge tone={s.tone} className={severity === 'CRITICAL' ? 'font-semibold' : undefined}>
      {s.label}
    </Badge>
  );
}

/** Provenance label — every price / booking / tracking event shows where it came from. */
export function SourceBadge({ sourceType, compact }: { sourceType: QuoteSourceType; compact?: boolean }) {
  const s = SOURCE[sourceType];
  return (
    <Badge tone={s.tone} title={s.description} className="font-mono text-[10.5px] tracking-wider uppercase">
      {sourceType === 'SIMULATED' && <FlaskConical className="h-3 w-3" aria-hidden />}
      {compact ? s.short : s.label}
    </Badge>
  );
}

export function SimulatedTag({ label = 'Simulated' }: { label?: string }) {
  return (
    <Badge tone="sim" title="Generated by the Fluxora simulator for demonstration — not real carrier data" className="font-mono text-[10.5px] tracking-wider uppercase">
      <FlaskConical className="h-3 w-3" aria-hidden />
      {label}
    </Badge>
  );
}
