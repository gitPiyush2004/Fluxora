async function resetDemoData() {
  const orgs = await Organization.find({ slug: { $regex: /^demo-/ } }).select('_id').lean();
  const ids = orgs.map((o) => o._id);
  const users = await User.find({ isDemoUser: true }).select('_id').lean();
  // Append-only collections block deleteMany through Mongoose middleware; use the driver for demo cleanup.
  await Promise.all([
    ShipmentEvent.collection.deleteMany({ organizationId: { $in: ids } }),
    AuditLog.collection.deleteMany({ organizationId: { $in: ids } }),
    Alert.deleteMany({ organizationId: { $in: ids } }),
    Shipment.deleteMany({ organizationId: { $in: ids } }),
    CarrierQuote.deleteMany({ organizationId: { $in: ids } }),
    QuoteRequest.deleteMany({ organizationId: { $in: ids } }),
    BookingRecord.deleteMany({ organizationId: { $in: ids } }),
    PurchaseOrder.deleteMany({ organizationId: { $in: ids } }),
    Product.deleteMany({ organizationId: { $in: ids } }),
    Supplier.deleteMany({ organizationId: { $in: ids } }),
    Counter.deleteMany({ organizationId: { $in: ids } }),
    Invite.deleteMany({ organizationId: { $in: ids } }),
    Membership.deleteMany({ $or: [{ organizationId: { $in: ids } }, { userId: { $in: users.map((u) => u._id) } }] }),
  ]);
  await Organization.deleteMany({ _id: { $in: ids } });
  await User.deleteMany({ isDemoUser: true });
}

