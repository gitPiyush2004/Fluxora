type SupplierMap = Record<string, { _id: Types.ObjectId; name: string; city: string; country: string; postalCode?: string | null; address?: string | null }>;

async function quoteAt(organizationId: Types.ObjectId, req: ShipmentRequest, at: Date, shipmentId: Types.ObjectId | undefined, userId: Types.ObjectId) {
  const adapters = SIM_PROFILES.map((p) => new SimulatedCarrierAdapter(p, () => at));
  const quotes: NormalizedQuote[] = (await Promise.all(adapters.map((a) => a.getQuotes(req)))).flat();
  const qrId = new Types.ObjectId();
  await QuoteRequest.collection.insertOne({
    _id: qrId,
    organizationId,
    shipmentId,
    request: { ...req, origin: { ...req.origin }, destination: { ...req.destination } },
    providers: SIM_PROFILES.map((p) => ({
      carrierCode: p.code, carrierName: p.name, provider: 'fluxora-simulator', mode: 'SIMULATED', status: 'OK',
      quoteCount: quotes.filter((q) => q.carrierCode === p.code).length, durationMs: 3, fromCache: false,
    })),
    createdBy: userId,
    createdAt: at,
  });
  const docs = quotes.map((q) => ({
    _id: new Types.ObjectId(),
    organizationId,
    quoteRequestId: qrId,
    shipmentId,
    carrierCode: q.carrierCode,
    carrierName: q.carrierName,
    serviceCode: q.serviceCode,
    serviceName: q.serviceName,
    serviceLevel: q.serviceLevel,
    currency: q.currency,
    totalMinor: q.totalMinor,
    breakdown: q.breakdown,
    transitDays: q.transitDays,
    estimatedDeliveryDate: q.estimatedDeliveryDate ? new Date(q.estimatedDeliveryDate) : undefined,
    billableWeightKg: q.billableWeightKg,
    volumetricWeightKg: q.volumetricWeightKg ?? undefined,
    constraints: q.constraints,
    provenance: { ...q.provenance, retrievedAt: new Date(q.provenance.retrievedAt), validUntil: q.provenance.validUntil ? new Date(q.provenance.validUntil) : undefined },
    eligibility: checkEligibility(q, req, at),
    reliability: { sampleSize: 0, minSamples: 5 },
    createdAt: at,
  }));
  await CarrierQuote.collection.insertMany(docs);
  return docs;
}

interface ShipmentPlan {
  ref: string;
  lane: Lane;
  carrier: CarrierCode;
  createdAt: Date;
  /** null = still planning; 'QUOTED' = offer selected, not booked */
  stage: 'DRAFT' | 'QUOTED' | 'BOOKED';
  outcome?: SimOutcome;
  purchaseOrder?: { _id: Types.ObjectId; poNumber: string; lines: { _id: Types.ObjectId; description: string; quantity: number; sku?: string | null; unitOfMeasure?: string | null }[] };
  cancelled?: boolean;
  /** Booked offline and tracked by hand: the last update stays until someone records another (stuck, delayed, customs hold). */
  manual?: { status: 'IN_TRANSIT' | 'DELAYED' | 'EXCEPTION'; description: string; at: Date };
}

async function createDemoShipment(organizationId: Types.ObjectId, userId: Types.ObjectId, plan: ShipmentPlan) {
  const { lane } = plan;
  const s = lane.origin;
  const req: ShipmentRequest = {
    origin: { city: s.city, postalCode: s.postalCode, country: s.country },
    destination: { city: lane.destination.city, postalCode: lane.destination.postalCode, country: lane.destination.country },
    shipmentType: lane.shipmentType,
    packageCount: lane.packageCount,
    actualWeightKg: lane.weightKg,
    lengthCm: lane.dims[0], widthCm: lane.dims[1], heightCm: lane.dims[2],
    insuranceRequired: false,
    specialHandling: [],
    currency: lane.currency,
    shipDate: plan.createdAt,
  };
  const shipmentId = new Types.ObjectId();
  const weight = calculateBillableWeight({ actualWeightKg: lane.weightKg, packageCount: lane.packageCount, lengthCm: lane.dims[0], widthCm: lane.dims[1], heightCm: lane.dims[2], divisor: 5000 });
  const base = {
    _id: shipmentId,
    organizationId,
    reference: plan.ref,
    purchaseOrderId: plan.purchaseOrder?._id,
    purchaseOrderNumber: plan.purchaseOrder?.poNumber,
    origin: s,
    destination: lane.destination,
    shipmentType: lane.shipmentType,
    packageCount: lane.packageCount,
    actualWeightKg: lane.weightKg,
    lengthCm: lane.dims[0], widthCm: lane.dims[1], heightCm: lane.dims[2],
    volumetricWeightKg: weight.volumetricWeightKg ?? undefined,
    billableWeightKg: weight.billableWeightKg,
    servicePreference: lane.level,
    insuranceRequired: false,
    specialHandling: [],
    currency: lane.currency,
    items: plan.purchaseOrder
      ? plan.purchaseOrder.lines.map((l) => ({ poLineId: l._id, sku: l.sku ?? undefined, description: l.description, quantity: l.quantity, unitOfMeasure: l.unitOfMeasure ?? undefined }))
      : [],
    contentsDescription: plan.purchaseOrder ? plan.purchaseOrder.lines.map((l) => `${l.quantity} × ${l.description}`).join('; ').slice(0, 500) : lane.contents,
    specUpdatedAt: new Date(0),
    trackingMode: 'NONE',
    createdBy: userId,
    isDemo: true,
    createdAt: plan.createdAt,
    updatedAt: plan.createdAt,
    __v: 0,
  };
  const events: Record<string, unknown>[] = [];
  const ev = (e: Record<string, unknown>) =>
    events.push({ _id: new Types.ObjectId(), organizationId, shipmentId, recordedAt: e.occurredAt, isException: false, ...e });
  ev({ type: 'CREATED', description: plan.purchaseOrder ? `Shipment created from purchase order ${plan.purchaseOrder.poNumber}` : 'Shipment created', occurredAt: plan.createdAt, newStatus: 'DRAFT', source: { type: 'USER', isSimulated: false }, actorId: userId, actorName: ADMIN_NAME });

  if (plan.stage === 'DRAFT') {
    await Shipment.collection.insertOne({ ...base, status: 'DRAFT', statusChangedAt: plan.createdAt });
    await ShipmentEvent.collection.insertMany(events);
    return;
  }

  const quoteAtTime = new Date(plan.createdAt.getTime() + 20 * 60_000);
  const quotes = await quoteAt(organizationId, { ...req, servicePreference: lane.level }, quoteAtTime, shipmentId, userId);
  const eligible = quotes.filter((q) => q.eligibility.eligible);
  const chosen = eligible.find((q) => q.carrierCode === plan.carrier) ?? eligible.sort((a, b) => a.totalMinor - b.totalMinor)[0];
  if (!chosen) throw new Error(`No eligible simulated offer for ${plan.ref}`);
  const selectedAt = new Date(quoteAtTime.getTime() + 15 * 60_000);
  ev({ type: 'QUOTE_SELECTED', description: `Selected ${chosen.carrierName} ${chosen.serviceName} (sample rate)`, occurredAt: selectedAt, previousStatus: 'DRAFT', newStatus: 'QUOTED', source: { type: 'USER', isSimulated: true }, actorId: userId, actorName: ADMIN_NAME });

  const selection = {
    selectedQuoteId: chosen._id,
    carrierCode: chosen.carrierCode,
    carrierName: chosen.carrierName,
    serviceName: chosen.serviceName,
    serviceLevel: chosen.serviceLevel,
    quoteSourceType: 'SIMULATED',
    quoteIsSimulated: true,
    freightCostMinor: chosen.totalMinor,
    expectedDeliveryDate: chosen.estimatedDeliveryDate,
  };

  if (plan.stage === 'QUOTED') {
    await Shipment.collection.insertOne({ ...base, ...selection, status: 'QUOTED', statusChangedAt: selectedAt, updatedAt: selectedAt });
    await ShipmentEvent.collection.insertMany(events);
    return;
  }

  const bookedAt = new Date(selectedAt.getTime() + 30 * 60_000);
  const trackingNumber = String(Math.floor(seededUnit(plan.ref) * 1e10)).padStart(10, '0');
  const bookingReference = `BK-${chosen.carrierCode}-${plan.ref.slice(-6)}`;
  ev({ type: 'BOOKED', description: `Sample booking ${bookingReference} created — nothing was booked with the carrier`, occurredAt: bookedAt, previousStatus: 'QUOTED', newStatus: 'BOOKED', source: { type: 'SIMULATED', provider: 'fluxora-simulator', isSimulated: true }, actorId: userId, actorName: ADMIN_NAME, metadata: { bookingReference, trackingNumber } });

  let status: ShipmentStatus = 'BOOKED';
  let statusChangedAt = bookedAt;
  let pickedUpAt: Date | undefined;
  let deliveredAt: Date | undefined;
  let lastTrackingUpdateAt: Date | undefined;
  let lastKnownLocation: string | undefined;
  let step = 0;

  if (plan.manual) {
    const { status: manualStatus, description, at } = plan.manual;
    const where = manualStatus === 'EXCEPTION' ? lane.destination : s; // customs holds happen at destination
    ev({ type: 'STATUS_CHANGE', description, occurredAt: at, location: { city: where.city, country: where.country }, previousStatus: 'BOOKED', newStatus: manualStatus, isException: manualStatus !== 'IN_TRANSIT', source: { type: 'USER', isSimulated: false }, actorId: userId, actorName: MEMBER_NAME });
    await Shipment.collection.insertOne({
      ...base, ...selection, status: manualStatus, statusChangedAt: at, pickedUpAt: at,
      booking: { reference: `${chosen.carrierCode}-${plan.ref.slice(-6)}`, bookedAt, provider: 'manual', isSimulated: false, cancellable: true },
      trackingMode: 'MANUAL', lastTrackingUpdateAt: at, lastKnownLocation: `${where.city}, ${where.country}`, updatedAt: at,
    });
    await ShipmentEvent.collection.insertMany(events);
    return;
  }

  if (plan.cancelled) {
    const at = new Date(bookedAt.getTime() + 3 * HOUR_MS);
    ev({ type: 'CANCELLED', description: `Sample booking ${bookingReference} cancelled. Reason: supplier delayed production`, occurredAt: at, previousStatus: 'BOOKED', newStatus: 'CANCELLED', source: { type: 'USER', isSimulated: true }, actorId: userId });
    status = 'CANCELLED';
    statusChangedAt = at;
  } else {
    const steps = planSimulatedJourney({
      trackingNumber,
      bookedAt,
      expectedDeliveryDate: chosen.estimatedDeliveryDate,
      origin: req.origin,
      destination: req.destination,
      simulationOutcome: plan.outcome ?? 'ON_TIME',
    });
    steps.forEach((st, i) => {
      if (st.at > NOW.getTime()) return;
      const at = new Date(st.at);
      const canMove = !!st.status && st.status !== status && canTransitionShipment(status, st.status);
      ev({
        type: canMove ? 'STATUS_CHANGE' : 'TRACKING',
        description: st.description,
        occurredAt: at,
        location: { city: st.city, country: st.country },
        previousStatus: canMove ? status : undefined,
        newStatus: canMove ? st.status : undefined,
        source: { type: 'SIMULATED', provider: 'fluxora-simulator', isSimulated: true },
        externalEventId: `${trackingNumber}:${i}`,
        isException: !!st.isException,
      });
      if (canMove) {
        status = st.status!;
        statusChangedAt = at;
        if (!pickedUpAt && ['PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED'].includes(st.status!)) pickedUpAt = at;
        if (st.status === 'DELIVERED') deliveredAt = at;
      }
      lastTrackingUpdateAt = at;
      lastKnownLocation = [st.city, st.country].filter(Boolean).join(', ');
      step = i + 1;
    });
  }

  await Shipment.collection.insertOne({
    ...base,
    ...selection,
    status,
    statusChangedAt,
    booking: { reference: bookingReference, bookedAt, provider: 'fluxora-simulator', isSimulated: true, cancellable: true },
    trackingNumber,
    trackingMode: 'SIMULATED',
    simulation: { nextStep: step, outcome: plan.outcome ?? 'ON_TIME' },
    pickedUpAt,
    deliveredAt,
    lastTrackingUpdateAt,
    lastTrackingPollAt: lastTrackingUpdateAt,
    lastKnownLocation,
    cancelledAt: status === 'CANCELLED' ? statusChangedAt : undefined,
    updatedAt: statusChangedAt,
  });
  await ShipmentEvent.collection.insertMany(events);
}

