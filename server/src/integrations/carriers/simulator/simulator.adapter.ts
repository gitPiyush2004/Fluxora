import { calculateBillableWeight } from '../../../modules/carriers/billable-weight.js';
import { addBusinessDays, seededUnit, stableHash } from '../../../utils/dates.js';
import { routeZone } from '../../../utils/geo.js';
import { CURRENCY_EXPONENT, type Currency } from '../../../utils/money.js';
import type {
  BookingRequest,
  BookingResult,
  CarrierAdapter,
  CarrierCapabilities,
  ChargeLine,
  NormalizedQuote,
  NormalizedTrackingEvent,
  Provenance,
  ShipmentRequest,
  TrackingContext,
} from '../types.js';
import {
  FUEL_SURCHARGE_RATE,
  INSURANCE_MIN_USD,
  INSURANCE_RATE,
  SIM_CURRENCY_FACTORS,
  SURCHARGES_USD,
  type SimProfile,
} from './profiles.js';
import { buildSimulatedTrackingEvents, SIMULATOR_PROVIDER_ID } from './simulated-tracking.js';
const QUOTE_VALIDITY_MS = 30 * 60_000;

const LIMITATIONS = [
  'Sample rate generated by Fluxora — not an offer from the carrier.',
  'Prices, transit times and service limits are illustrative and not based on carrier tariffs.',
];

function provenance(now: Date, extra?: Partial<Provenance>): Provenance {
  return {
    sourceType: 'SIMULATED',
    provider: SIMULATOR_PROVIDER_ID,
    retrievedAt: now.toISOString(),
    isSimulated: true,
    validUntil: new Date(now.getTime() + QUOTE_VALIDITY_MS).toISOString(),
    limitations: LIMITATIONS,
    ...extra,
  };
}

function toMinorIn(usd: number, currency: Currency): number {
  const major = usd * (SIM_CURRENCY_FACTORS[currency] ?? 1);
  return Math.round(major * 10 ** CURRENCY_EXPONENT[currency]);
}

/**
 * Deterministic carrier simulator. Identical requests produce identical prices, so
 * results are cache-friendly and testable. One instance per carrier profile.
 */
export class SimulatedCarrierAdapter implements CarrierAdapter {
  readonly providerId = SIMULATOR_PROVIDER_ID;
  readonly mode = 'SIMULATED' as const;
  readonly code;
  readonly name;
  readonly capabilities: CarrierCapabilities;

  constructor(
    private readonly profile: SimProfile,
    private readonly clock: () => Date = () => new Date(),
  ) {
    this.code = profile.code;
    this.name = profile.name;
    this.capabilities = { quotes: true, booking: true, tracking: true, cancellation: profile.supportsCancellation };
  }

  async getQuotes(req: ShipmentRequest): Promise<NormalizedQuote[]> {
    const now = this.clock();
    const zone = routeZone(req.origin.country, req.destination.country);
    const routeKey = `${req.origin.country}|${req.origin.city.toLowerCase()}|${req.destination.country}|${req.destination.city.toLowerCase()}`;

    return this.profile.services.map((svc) => {
      const weight = calculateBillableWeight({
        actualWeightKg: req.actualWeightKg,
        packageCount: req.packageCount,
        lengthCm: req.lengthCm,
        widthCm: req.widthCm,
        heightCm: req.heightCm,
        divisor: svc.divisor,
        roundingIncrementKg: svc.roundingKg,
      });
      // ±5% deterministic route variation so lanes don't all price identically.
      const variation = 0.95 + seededUnit(`${svc.code}|${routeKey}`) * 0.1;
      const freightUsd = Math.max(svc.minChargeUsd, (svc.base[zone] + svc.perKg[zone] * weight.billableWeightKg) * this.profile.priceFactor * variation);

      const breakdown: ChargeLine[] = [{ label: 'Base freight', amountMinor: toMinorIn(freightUsd, req.currency) }];
      breakdown.push({ label: 'Fuel surcharge', amountMinor: toMinorIn(freightUsd * FUEL_SURCHARGE_RATE, req.currency) });
      for (const s of req.specialHandling) {
        if (svc.specialHandling.includes(s)) {
          breakdown.push({ label: `Handling: ${s.replace(/_/g, ' ').toLowerCase()}`, amountMinor: toMinorIn(SURCHARGES_USD[s], req.currency) });
        }
      }
      if (req.insuranceRequired && req.cargoValueMinor) {
        const cargoCurrency = req.cargoCurrency ?? req.currency;
        const cargoUsd = req.cargoValueMinor / 10 ** CURRENCY_EXPONENT[cargoCurrency] / (SIM_CURRENCY_FACTORS[cargoCurrency] ?? 1);
        breakdown.push({ label: 'Cargo insurance', amountMinor: toMinorIn(Math.max(INSURANCE_MIN_USD, cargoUsd * INSURANCE_RATE), req.currency) });
      }
      const totalMinor = breakdown.reduce((a, b) => a + b.amountMinor, 0);

      const transitDays = svc.transitDays[zone];
      const eta = addBusinessDays(req.shipDate, transitDays);
      eta.setUTCHours(17, 0, 0, 0);

      return {
        carrierCode: this.profile.code,
        carrierName: this.profile.name,
        serviceCode: svc.code,
        serviceName: svc.name,
        serviceLevel: svc.level,
        currency: req.currency,
        totalMinor,
        breakdown,
        transitDays,
        estimatedDeliveryDate: eta.toISOString(),
        billableWeightKg: weight.billableWeightKg,
        volumetricWeightKg: weight.volumetricWeightKg,
        constraints: {
          shipmentTypes: svc.shipmentTypes,
          maxWeightPerPackageKg: svc.maxWeightPerPackageKg,
          maxTotalWeightKg: svc.maxTotalWeightKg,
          maxLengthCm: svc.maxLengthCm,
          specialHandling: svc.specialHandling,
        },
        provenance: provenance(now, {
          limitations: [...LIMITATIONS, `Billable weight estimated with divisor ${svc.divisor} (${weight.basis.toLowerCase()} weight basis).`],
        }),
      } satisfies NormalizedQuote;
    });
  }

  async bookShipment(booking: BookingRequest): Promise<BookingResult> {
    const now = this.clock();
    const h = stableHash(`${booking.idempotencyKey}|${booking.shipmentReference}`).toString(36).toUpperCase().padStart(7, '0');
    const trackingDigits = String(stableHash(`trk|${booking.idempotencyKey}`)).padStart(10, '0').slice(0, 10);
    const eta = booking.quote.transitDays != null ? addBusinessDays(now, booking.quote.transitDays) : null;
    eta?.setUTCHours(17, 0, 0, 0);
    return {
      bookingReference: `BK-${this.profile.code}-${h}`,
      trackingNumber: trackingDigits,
      expectedDeliveryDate: eta?.toISOString() ?? booking.quote.estimatedDeliveryDate ?? undefined,
      isSimulated: true,
      cancellable: this.profile.supportsCancellation,
      provenance: provenance(now, { validUntil: undefined, limitations: ['Sample booking — nothing was booked with the carrier.'] }),
    };
  }

  async getTracking(context: TrackingContext): Promise<NormalizedTrackingEvent[]> {
    return buildSimulatedTrackingEvents(context, this.clock());
  }

  async cancelBooking(bookingReference: string): Promise<{ cancelled: boolean; message?: string }> {
    if (!this.profile.supportsCancellation) {
      return { cancelled: false, message: `${this.profile.name} sample bookings cannot be cancelled` };
    }
    return { cancelled: true, message: `Sample booking ${bookingReference} cancelled` };
  }
}
